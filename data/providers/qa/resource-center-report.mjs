// A-007: derived inventory counts, immutable A-006 baseline, query-only resource guard.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
export const canonical = value => JSON.stringify(value && typeof value === 'object' ? Array.isArray(value) ? value.map(v => JSON.parse(canonical(v))) : Object.fromEntries(Object.keys(value).sort().map(k => [k, JSON.parse(canonical(value[k]))])) : value);
export const fingerprint = value => createHash('sha256').update(canonical(value)).digest('hex');
export function inspect(dataset, baseline) {
  const errors = [];
  for (const [file, rows] of Object.entries(baseline.files)) {
    const current = new Map(dataset[file].map(row => [row.id, row]));
    for (const row of rows) {
      if (!current.has(row.id)) errors.push(`Original record removed: ${file}/${row.id}`);
      else if (fingerprint(current.get(row.id)) !== row.fingerprint) errors.push(`Original record changed: ${file}/${row.id}`);
    }
  }
  const centers = dataset['providers.json'].filter(p => p.resourceCategory === 'ASSISTIVE_DEVICE_CENTER');
  const ids = new Set(centers.map(p => p.id));
  for (const id of ['TP-ARC-001', 'TP-ARC-002', 'TP-ARC-003', 'NTPC-ARC-001', 'NTPC-ARC-002']) if (!ids.has(id)) errors.push(`Original center removed: ${id}`);
  for (const center of centers) if (center.type !== 'OTHER' || !['臺北市', '新北市'].includes(center.city)) errors.push(`Invalid query-only center: ${center.id}`);
  for (const service of dataset['provider-services.json']) if (ids.has(service.providerId)) errors.push(`Center must not enter recommendation/matching: ${service.providerId}`);
  const lines = ['<!-- A007:BEGIN statistics -->', '## Generated inventory', '', 'Generated by `node data/providers/qa/resource-center-report.mjs --write`; check with the same command without `--write`.', '', '| Inventory | Count |', '|---|---:|',
    `| All providers/resources | ${dataset['providers.json'].length} |`,
    `| Original service providers retained | ${baseline.files['providers.json'].length} |`,
    `| Assistive-device resource centers (query only) | ${centers.length} |`,
    `| Taipei centers | ${centers.filter(p => p.city === '臺北市').length} |`,
    `| New Taipei centers | ${centers.filter(p => p.city === '新北市').length} |`,
    `| Provider services | ${dataset['provider-services.json'].length} |`,
    `| Confirmed service-area rows | ${dataset['provider-service-areas.json'].filter(a => a.active).length} |`,
    `| Contract-region rows | ${dataset['provider-contract-regions.json'].length} |`,
    `| Centers with coordinates | ${centers.filter(p => p.lat !== null && p.lng !== null).length} |`,
    `| Centers awaiting coordinates | ${centers.filter(p => p.lat === null || p.lng === null).length} |`,
    `| Original baseline integrity | ${errors.length === 0 ? 'PASS' : 'FAIL'} |`,
    '<!-- A007:END statistics -->'];
  return { errors, section: lines.join('\n') };
}
export function syncReport(report, section, write) {
  const block = /<!-- A007:BEGIN statistics -->[\s\S]*?<!-- A007:END statistics -->/;
  const match = report.match(block);
  if (write) return { text: match ? report.replace(block, section) : `${report.trimEnd()}\n\n${section}\n`, errors: [] };
  return { text: report, errors: match?.[0] === section ? [] : ['Generated A-007 statistics are missing or stale'] };
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const baseline = JSON.parse(readFileSync(resolve(root, 'qa/a-007-baseline.json'), 'utf8'));
  const dataset = Object.fromEntries(Object.keys(baseline.files).map(file => [file, JSON.parse(readFileSync(resolve(root, 'staging', file), 'utf8'))]));
  const result = inspect(dataset, baseline);
  const reportFile = resolve(root, 'qa/resource-center-report.md');
  const report = syncReport(readFileSync(reportFile, 'utf8'), result.section, process.argv.includes('--write') && result.errors.length === 0);
  if (process.argv.includes('--write') && result.errors.length === 0) writeFileSync(reportFile, report.text);
  const errors = [...result.errors, ...report.errors];
  for (const error of errors) console.error(error);
  console.log(`A-007 report: ${errors.length ? 'FAIL' : 'PASS'}`);
  process.exitCode = errors.length ? 1 : 0;
}
